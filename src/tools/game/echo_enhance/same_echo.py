# -*- coding: utf-8 -*-
"""★★★ 「同种声骸」识别与批量解锁 —— 用户 2026-10-28 的需求。

## 用户原话

> ①理解对的
> ②你忘记3C是筛选2个吗，一个攻击词条，一个属性伤害词条，
> 所以同种3C一般是有2个的

> 需要识别同种声骸，但其实只需要识别右边那个是不是一样的就行

## 业务背景

3C 配置里每种声骸选 **2 个主属性**（如 攻击% + 导电伤害%）::

    解形煞  →  攻击百分比  +  导电伤害加成
    ↓ 游戏里因此有 2 个「解形煞」卡片（各一个主属性）
    ↓

强化好其中一个（把词条刷到符合条件）→ **另一个也不该再强化**
（这套配置要的 2 个主属性都齐了，再刷纯浪费材料）

## 用户给的关键提示

> 其实只需要识别右边那个是不是一样的就行

**不用做图标匹配**，只要读**右侧详情面板里的大字名字**：

    ┌─────────────────────────┐
    │  解形煞                  │   ← 这里，OCR 读它
    │  +0                      │
    │  COST 3                  │
    │  持有数量: 11            │
    └─────────────────────────┘

真机截图（1920x1080）实测，「解形煞」这几个字：
    x ≈ 1180~1320    y ≈ 130~180

比图标匹配可靠得多（字大、对比度高、不怕背景光效）。

## 实现路径

    1. 强化完一个 → 它的名字还在右侧面板上（ESC 退回列表后仍在）
    2. OCR 读名字 → "解形煞"
    3. 扫 6x3 = 18 个格子，逐个点开 → 读右边名字 → 比对
    4. 名字一样的 → 按 C 解锁
    5. 继续下一个

## ⚠ 代价

逐个点开 18 格 + OCR，每个格子约 0.6~1 秒 → 一轮扫描 10~18 秒。
只在**真的强化成功**（`hit=True`）时才做，不是每个声骸都扫。
"""
from __future__ import annotations

import re

#: **列表页**右侧详情面板上「声骸名」的 OCR 区域（相对坐标，1920x1080 实测）
#:
#: 用户截图（2026-10-28）里「解形煞」的位置：
#:     x 1180~1320 / 1920 = 0.615~0.688
#:     y  130~180  / 1080 = 0.120~0.167
#:
#: 各边留余量（名字长短不一，如「共鸣回响·天演溯心」比「解形煞」长得多）
ECHO_NAME_REGION = (0.60, 0.10, 0.85, 0.19)

#: **强化界面**里「声骸名」的 OCR 区域（相对坐标）。
#:
#: ## ⚠⚠ 为什么需要第二个区域（2026-10-30 实机发现）
#:
#: 两个界面的**布局完全不同**：
#:
#: ==========  ==========================================
#: 列表页      名字在**右侧**详情面板（x≈0.60~0.85）
#: 强化界面    名字在**左上角**标题（x≈0.09~0.17）
#: ==========  ==========================================
#:
#: 用户 2026-10-30 的强化界面截图：「融躯战士」在
#: **x≈180~310、y≈138~182**（1920x1080 下）。
#: 换算相对坐标 ``(0.094, 0.128) ~ (0.161, 0.169)``。
#:
#: ## ⚠ 区域要**窄**，别图省事放宽
#:
#: 一开始开到 ``(0.07, 0.10, 0.45, 0.19)``（x 134~864），结果把
#: 右边的「0/400」「攻击 3.6%」以及下面那些
#: **「强化至」「强化消耗材料」「不限」「阶段放入」**也读进来了 ——
#: 实测这几个**都能通过** ``looks_like_echo_name``（有中文、无数字、
#: 不在黑名单里），于是候选列表被杂物塞满。
#:
#: 现在收到刚好罩住名字那一行：
#: ``(0.088, 0.118, 0.30, 0.180)`` → 像素 x 169~576、y 127~194。
#: 右边留到 0.30 是为了容纳长名字（「共鸣回响·鸣式·虚造神型」）。
ENHANCE_NAME_REGION = (0.088, 0.118, 0.30, 0.180)

#: 名字的最短长度（少于这个多半是 OCR 噪声）
MIN_NAME_LEN = 2

#: 扫描所有格子时，每个格子"点开 + 读名字"要等多久
#:
#: 点一下卡片右侧详情会刷新，OCR 要等它渲染完。
#: 实测 0.5 秒够；太快会读到上一张卡的名字（**这是最容易出的错**）。
CARD_OPEN_WAIT = 0.5

#: 名字比对：去掉空白/标点后完全相等才算同种
#:
#: 为什么不用模糊匹配（如 SequenceMatcher）：
#: 「解形煞」和「绝息魄」差异明显，但「小翼龙·衍射」和「小翼龙·热熔」
#: 只差两个字 —— 模糊匹配会把它们当同一个，那就**锁错声骸**了。
_STRIP = re.compile(r"[\s·・:：,，。.、\-—_()（）\[\]【】]")

#: 「异相」前缀 —— 游戏里同一个声骸的特殊版本（换皮/异色），**算同一种**。
#:
#: ## 用户 2026-10-30 明确说明
#:
#: > 是同一个，而且所有前面加了异相的，其实都是同一个声骸
#:
#: ## 实机症状（2026-10-30 16:2x）
#:
#: 配置里勾的是「封庭械囿」，游戏里那张卡显示 **「异相·封庭械囿」**
#: → 归一化后 ``异相封庭械囿`` ≠ ``封庭械囿``
#: → `_skip_reason` 判"配置里没勾选这个声骸" → **跳过**
#: → 用户看到的是"3C 强化好一个就开始乱跳，连该强的也跳了"。
#:
#: ## ⚠⚠ OCR 会把「异」读成繁体「異」（2026-10-30 16:58 实机）
#:
#: 日志里明明写着::
#:
#:     「異相・封庭械囿」配置里没勾选这个声骸 → 点下一个声骸，跳过它
#:
#: 注意那个 **「異」** —— OCR 出来的是**繁体**，而我剥前缀用的是简体
#: 「异相」→ 匹配不上 → 没剥掉 → 判"不在白名单" → 跳过。
#:
#: 引擎语言是 en_US（日志里那条 ⚠ 一直有），OCR 模型对简繁不敏感，
#: 同一个字经常简繁混出。所以前缀要**简繁都认**。
#:
#: 顺便：既然 OCR 会混出繁体，**声骸名本身**也可能出现繁体字
#: （如「鐵」「龍」）→ 那就需要整串繁简归一。
#: 见 :func:`_to_simplified`。
_ELITE_PREFIXES = ("异相", "異相")

#: 常见繁→简对照（只收这个游戏声骸名/界面里真会出现的）。
#:
#: 为什么不做完整繁简转换：不想为了这一件事引入整个 opencc 依赖
#: （几十 MB），而声骸名里会出现的繁体字就那些。**缺了就补**。
_TRAD_TO_SIMP = str.maketrans({
    "異": "异", "體": "体", "龍": "龙", "鐵": "铁", "劍": "剑",
    "風": "风", "霜": "霜", "雲": "云", "電": "电", "雷": "雷",
    "靈": "灵", "獸": "兽", "戰": "战", "軍": "军", "將": "将",
    "衛": "卫", "門": "门", "開": "开", "關": "关", "閉": "闭",
    "鳥": "鸟", "魚": "鱼", "馬": "马", "貝": "贝", "車": "车",
    "輪": "轮", "機": "机", "鐵": "铁", "鋼": "钢", "銀": "银",
    "銅": "铜", "黃": "黄", "綠": "绿", "藍": "蓝", "紅": "红",
    "聲": "声", "骸": "骸", "調": "调", "諧": "谐", "強": "强",
    "化": "化", "級": "级", "頭": "头", "帶": "带", "護": "护",
    "傷": "伤", "擊": "击", "術": "术", "効": "效", "數": "数",
    "量": "量", "質": "质", "點": "点", "轉": "转", "換": "换",
    "選": "选", "擇": "择", "確": "确", "認": "认", "準": "准",
    "備": "备", "練": "练", "習": "习", "寶": "宝", "蔵": "藏",
    "藏": "藏", "庫": "库", "裝": "装", "備": "备", "備": "备",
})


def _to_simplified(text: str) -> str:
    """把常见繁体字换成简体 —— OCR 简繁混出时用来对齐。"""
    return text.translate(_TRAD_TO_SIMP)


def normalize_echo_name(text: str) -> str:
    """去掉空白和标点、统一简繁、剥掉「异相」前缀 —— 用于严格比对。

    ⚠ 「异相」是这个游戏的**同种声骸换皮版本**，用户明确要求算同一种
    （见 ``_ELITE_PREFIXES`` 的说明）。所以这里统一剥掉，
    这样「异相·封庭械囿」和「封庭械囿」会归一化成同一个键。

    ⚠⚠ OCR 会简繁混出（实测把「异相」读成「異相」），所以先做一遍
    繁→简，再做前缀判断和比较 —— 否则「異相封庭械囿」永远匹配不上
    「封庭械囿」。
    """
    name = _STRIP.sub("", _to_simplified(str(text or "")))
    for prefix in _ELITE_PREFIXES:
        if name.startswith(prefix) and len(name) > len(prefix) + MIN_NAME_LEN:
            name = name[len(prefix):]
            break
    return name


def same_echo(a: str, b: str) -> bool:
    """两个名字是不是**同一种声骸**（严格相等）。"""
    na, nb = normalize_echo_name(a), normalize_echo_name(b)
    if len(na) < MIN_NAME_LEN or len(nb) < MIN_NAME_LEN:
        return False
    return na == nb


#: 已知的界面文字（不是声骸名）—— 归一化后再比
#:
#: ⚠ 这几个都是实际 OCR 会读到的（实测见 2026-10-28 的单测）：
#: ``持有数量11`` 是卡片右下角那行，``调谐成功`` 是强化后的弹窗，
#: ``攻击`` 是词条名。不排除它们的话会被当成声骸名拿去比对。
_NOT_NAMES = frozenset({
    "声骸", "声骸技能", "合鸣效果", "持有数量", "共鸣效果",
    "强化", "调谐", "调谐成功", "培养", "声骸强化",
    "攻击", "生命", "防御", "暴击", "暴击伤害",
    "攻击百分比", "生命百分比", "防御百分比",
    "共鸣效率", "治疗加成", "能量回复",
    "主属性", "副属性", "词条", "等级",
    "点击任意位置返回", "不再提示", "本次登录不再提示",
})

#: 明显是界面文字的前缀/片段（归一化后匹配）
_NOT_NAME_PARTS = (
    "持有数量", "调谐成功", "不再提示", "点击任意",
    "属性加成", "伤害加成", "百分比",
    #: ★ 2026-10-30 实机补：这几个在**强化界面**会读到，
    #: 而且都能通过原来的过滤（有中文、无数字、不在 _NOT_NAMES 里），
    #: 把候选列表塞满杂物 → 白名单匹配全落空。
    "强化至", "强化消耗", "强化并", "调谐",
    "阶段放入", "快捷放入", "不限",
    "声骸强化", "声骸技能", "合鸣效果",
)


def looks_like_echo_name(text: str) -> bool:
    """这段 OCR 结果像不像一个声骸名（过滤掉 +0 / COST 3 / 持有数量 这些）。"""
    name = normalize_echo_name(text)
    if len(name) < MIN_NAME_LEN:
        return False
    #: 纯数字 / 纯符号 → 不是名字
    if not any("\u4e00" <= ch <= "\u9fff" for ch in name):
        return False
    #: 已知的界面文字
    if name in _NOT_NAMES:
        return False
    #: 含界面文字的片段（如「持有数量11」「导电伤害加成6.0」）
    if any(part in name for part in _NOT_NAME_PARTS):
        return False
    #: 带数字的（词条数值 / 等级）→ 不是纯名字
    if any(ch.isdigit() for ch in name):
        return False
    return True


def read_echo_name(task, known_names=None) -> str:
    """读当前声骸的名字。读不到返回空串。

    :param task: ok-ww 的任务实例（要有 ``ocr``）
    :param known_names: **已知的声骸名集合**（归一化后）。
        给了就**只接受列表里的名字** —— 这是 2026-10-30 的关键修复，
        见下面「为什么需要 known_names」。

    ## ★ 两个区域都试（2026-10-30 修）

    名字在**两个界面的位置完全不同**：

    * **列表页** → 右侧详情面板（:data:`ECHO_NAME_REGION`）
    * **强化界面** → 左上角标题（:data:`ENHANCE_NAME_REGION`）

    只试一个的话，在另一个界面永远读不到 → 跳过时记不下名字 →
    下一轮又强化同一个声骸（用户报的"跳过还是强化那个"就是这么来的）。

    ## ⚠⚠ 为什么需要 ``known_names``（2026-10-30 实机翻车的真因）

    ``looks_like_echo_name`` 只做**形状过滤**，它挡不住"长得像名字的
    界面文字"。实测：列表页右侧面板里 **「羽落空尘之歌」**（套装名，
    在「合鸣效果」那一栏下面）**完全通过** ``looks_like_echo_name``！

    而 :data:`ECHO_NAME_REGION` 那块区域（y 108~205）**同时罩住了**
    声骸名（y≈130~180）和套装名（y≈590 那个更下面，但 OCR 一整块读
    有时会把相邻行带进来）。

    后果（用户报的两个 bug 都是它）：
      * 读到套装名 → 白名单里没有 → 判"配置里没勾选" → **跳过本该强化的**
      * 读到套装名 → 套装名不在已处理集合 → 判"可强化" → 表面看正常，
        但**成套计数完全错乱**（把套装名当成声骸名记进 `_handled_echoes`）
      * 读到空 → `_skip_reason("")` 返回空 → **强化了不该强化的**
        （"配置里明明去掉了融躯战士，怎么还要强化他"）

    给了 ``known_names`` 后：只认**白名单里出现过的名字**，
    套装名/界面文字一律不算 —— 这是零成本、最可靠的校验。

    ⚠ 用**单帧** ``ocr``：这是"看一眼"的探针，等满超时会把每个
    声骸都拖慢 1 秒（同 ``_has_material_reset_button`` 的处理）。
    """
    known = {normalize_echo_name(n) for n in (known_names or ()) if n}
    #: ★★ 2026-10-30 诊断：把每个区域的**原始 OCR 文本**记下来，
    #: 读不到名字时打一行 —— 这是判断"区域不对"还是"名字对不上白名单"
    #: 的唯一办法（之前加白名单后一直读到空串，完全看不出原因）。
    _raw_debug: list[str] = []
    #: 所有区域都没白名单命中时的"退路"（第一个像名字的候选）
    _fallback: str | None = None
    for region in (ECHO_NAME_REGION, ENHANCE_NAME_REGION):
        try:
            lines = task.ocr(*region)
        except Exception as exc:  # noqa: BLE001 - 读不到就试下一个区域
            _raw_debug.append(f"{region[:2]}→异常{type(exc).__name__}")
            continue
        raw_texts = [str(getattr(x, "name", None) or x).strip() for x in (lines or ())]
        _raw_debug.append(f"{region[0]:.2f}→{raw_texts}")
        if not lines:
            continue
        candidates: list[str] = []
        for text in raw_texts:
            if not looks_like_echo_name(text):
                continue
            candidates.append(text)
        if not candidates:
            continue
        #: ★★ 2026-10-30 白名单不再"一票否决"，但**也不直接采信**：
        #:
        #: ## 三个 bug 的演进（这段别删，是踩出来的）
        #:
        #: **v1（一票否决）**：只接受白名单里的名字，读不到就返回空。
        #:   → 格子里是配置外的声骸（融躯战士）时读到空 → 上层跳过。
        #:   → 但 OCR 偶尔差一个字的白名单声骸也读到空 →
        #:     **任务一个都强化不了**（实机 2026-10-30 15:20：
        #:     连续 7 次「读不到声骸名」→ 跳过 8 个 → 自动停止）。
        #:
        #: **v2（无条件返回第一个候选）**：
        #:   → 列表页右侧那块区域**同时罩住了套装名**（y 108~205 把
        #:     「羽落空尘之歌」带进来了）→ 返回套装名 →
        #:     `_skip_reason` 判"不在白名单"→ **永远跳过，死循环**。
        #:
        #: **v3（现在）**：
        #:   * 白名单命中 → 立刻返回（最可信）
        #:   * 没命中 → **不急着返回，先试下一个区域**
        #:   * 所有区域都不命中 → 才退回"第一个候选"
        #:     （至少让上层能判，总比返回空好）
        #:
        #: 这样既不会因为套装名污染而死循环，也不会因为 OCR 差一个字
        #: 而整体瘫痪。
        if known:
            hit = next((t for t in candidates
                        if normalize_echo_name(t) in known), None)
            if hit:
                return hit
            #: 本区域没命中 → 记下候选，试下一个区域
            if _fallback is None:
                _fallback = candidates[0]
            continue
        return candidates[0]

    #: 所有区域都没白名单命中 → 退回第一个候选（让上层去判 + 记日志）
    if _fallback:
        return _fallback

    #: 全都没读到 → 打一行原始内容（只在有白名单时打，避免刷屏）
    if known:
        try:
            task.log_info("[读名字失败] " + " | ".join(_raw_debug))
        except Exception:  # noqa: BLE001
            pass
    return ""


def screen_looks_blank(task) -> bool:
    """画面是不是**整片黑**（游戏没渲染 / 刚切界面还没画出来）。

    ## 为什么需要（2026-10-30 实机定位到的死循环真因）

    用户按「跳过」后，任务进入「点培养 → 进强化界面」的循环。
    而**强化界面刚打开的一瞬间 WGC 捕获到的是黑帧** ——
    实机失败截图 ``data/okww/screenshots/15-35-56.639_…_original.png``
    **整张全黑**，只有左上角「声骸强化」几个字勉强可见。

    黑屏时 OCR 什么都读不到 → 读不到名字 → 判定"跳过" → Esc 退出
    → 又点培养 → 又黑 → 又跳过 …… **在声骸之间来回弹**，
    直到 ``MAX_CONSECUTIVE_SKIPS`` 把任务停掉。

    ## 判据

    取画面**中间一大块**（避开四周的 UI），算它的平均亮度。
    全黑的画面平均亮度接近 0（实机那张大约 8~15/255）。
    正常强化界面中间有声骸大图 + 星空背景，亮度明显更高。

    ⚠ 阈值取 40（0~255 制）—— 留足余量：正常界面最暗的深蓝背景
    也有 50~70，而黑帧不超过 20。

    :return: ``True`` = 画面是黑的（调用方应该**等**，不要判"跳过"）
    """
    try:
        import numpy as np  # noqa: PLC0415

        shot = task.screenshot()          #: numpy BGR 数组（ok-ww 的接口）
        if shot is None:
            return False
        h, w = shot.shape[:2]
        #: 中间那块（避开左边图标列和右边详情面板）
        patch = shot[int(h * 0.30):int(h * 0.70),
                     int(w * 0.30):int(w * 0.75)]
        if patch.size == 0:
            return False
        mean = float(np.mean(patch))
        if mean < 40:
            try:
                task.log_info(f"⚠ 画面偏黑（平均亮度 {mean:.1f}/255）"
                              f"→ 游戏可能没渲染/在切界面，先等待")
            except Exception:  # noqa: BLE001
                pass
            return True
        return False
    except Exception:  # noqa: BLE001 - 探测失败就当不黑（保持原行为）
        return False
