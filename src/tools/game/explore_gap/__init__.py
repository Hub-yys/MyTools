# -*- coding: utf-8 -*-
"""查缺补漏 —— 照攻略视频自动跑路线（视觉伺服，不用世界坐标）。

## 它解决什么

用户 2026-10-11：**"不，不需要什么坐标，我只需要你做一件事，查缺补漏"**

思路：视频里的画面**就是参照物**。不建立世界坐标，只持续回答一个
可观测的问题 —— "我现在屏幕上的画面 ≈ 视频第几秒的画面？"：:

    对上了 → 照参考往前走
    偏了   → 量出偏了多少、往哪边，纠回来

误差**不累积**（每帧重新对齐），这是它比"照着按键盲放"强的地方。

## 文件分工（★ 判断都在 core，本包只接线）

======================================  ==================================
文件                                     职责
======================================  ==================================
``core/explore_gap/descriptor.py``     一帧 → 定长向量（UI 遮罩）
``core/explore_gap/library.py``        参考库：建 / 存 / 读
``core/explore_gap/locate.py``         定位：连续性 + 先对齐再打分
``core/explore_gap/locator.py``        定位 + 测偏离 + 可信度闸门
``core/explore_gap/controller.py``     闭环决策（**纯函数**）
``executor.py``（本包）                 把决策变成按键/转向
``okww_task.py``（本包）                ok-ww 任务类（宿主接线）
``tool.py``（本包）                     工具页：建库 + 标定
======================================  ==================================

## ⚠ 现状：**执行层还没在真机验证过**

已经**离线验证透**的部分：

* 定位：非循环 ±2 命中 94.8%
* 闭环：误纠偏 0、跑飞 0、可用率 71%、残差最大 0.478px
* 决策：77 个单测 + 真视频闭环仿真

**没验证**的两件事（都需要真机）：

1. ``PX_PER_TURN_SEC``（像素 → 转向时长）—— 取决于灵敏度 / DPI / FOV
2. 前进一步对应多少画面时间

→ 所以本工具页**先提供"建库 + 标定 + 试跑"**，
   而不是"一键全自动"。

## 参数依据

所有常量都来自实测，见 ``docs/查缺补漏-实验记录.md``。
改常量前先读那份文档。
"""

from __future__ import annotations

__all__ = ["pick_library"]


def __getattr__(name: str):
    """延迟暴露常用符号（避免 import 时碰 cv2 / ok-ww）。"""
    if name == "pick_library":
        from .okww_task import pick_library      # noqa: PLC0415

        return pick_library
    raise AttributeError(name)
